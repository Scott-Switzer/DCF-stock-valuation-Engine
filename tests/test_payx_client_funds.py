"""PAYX client-funds reconciliation: filed numbers, no-double-count, valuation bridge.

The machine-readable evidence lives in
find/outputs/company-packets/payx-client-funds.json (regenerated by
scripts/reconcile_payx_client_funds.py from the original 10-K filings).
These tests pin the filed inputs, the retained Method A derivation, the
no-double-count identity, and the frozen-input valuation deltas so any future
change to cash/NWC handling is deliberate and re-quantified.
"""

import json
from pathlib import Path

EVIDENCE = Path("find/outputs/company-packets/payx-client-funds.json")


def evidence():
    return json.loads(EVIDENCE.read_text())


def test_filed_client_funds_inputs_are_pinned():
    filed = evidence()["filed_millions"]["2026-05-31"]
    assert filed["cash"] == 1088.2
    assert filed["peo_in_cash"] == 217.7
    assert filed["funds_held"] == 4832.2
    assert filed["client_obligations"] == 4884.6
    assert filed["current_assets"] == 8613.3
    assert filed["current_liab"] == 6840.6
    assert filed["debt_in_cl"] == 0.0


def test_retained_method_a_matches_packet_inputs():
    methods = evidence()["methods"]
    assert methods["A_current"]["nwc"] == [492.2, 750.0, 684.5]
    assert methods["A_current"]["cash"] == 1088.2
    assert methods["A_current"]["verdict"] == "retained"


def test_client_balances_enter_once_net_inside_nwc():
    # Bridge cash is plain reported cash; the fiduciary pair nets inside NWC
    # only: (CA - cash) - (CL - debt) with funds-held inside CA and the
    # obligation inside CL. No client balance touches enterprise value twice.
    filed = evidence()["filed_millions"]["2026-05-31"]
    net_client = round(filed["funds_held"] - filed["client_obligations"], 1)
    assert net_client == -52.4
    methods = evidence()["methods"]
    assert round(methods["A_current"]["nwc"][2] - methods["B2_ex_fiduciary"]["nwc"][2], 1) == round(net_client, 1)
    assert round(filed["cash"] + methods["A_current"]["nwc"][2], 1) == round(
        filed["current_assets"] - filed["current_liab"] + filed["debt_in_cl"], 1
    )


def test_frozen_harness_replicates_live_staging():
    doc = evidence()
    live = doc["live_staging_reference"]["intrinsic"]
    assert live == 88.01403475349672
    bridge = doc["valuation_bridge"]
    assert abs(bridge["A_current"]["intrinsic"] - live) / live < 1e-9


def test_valuation_deltas_are_quantified_and_small():
    bridge = evidence()["valuation_bridge"]
    # Fully filing-supported fiduciary carve-out: forecast-only effect.
    assert abs(bridge["B2_ex_fiduciary"]["intrinsic"] - 87.6380) < 0.001
    assert abs(bridge["B2_ex_fiduciary"]["delta_intrinsic_vs_A"] - (-0.3760)) < 0.001
    # Rejected asymmetric cash removal is exactly the disgorged float.
    assert abs(bridge["B1_cash_only_SENSITIVITY_REJECTED"]["delta_intrinsic_vs_A"] - (-217.7 / 360.0)) < 1e-9
    # Symmetric PEO carve-out needs an undisclosed liability split, so it
    # stays a sensitivity: its swing dwarfs the supported B2 effect.
    b3 = bridge["B3_peo_symmetric_SENSITIVITY"]["delta_intrinsic_vs_A"]
    b2 = bridge["B2_ex_fiduciary"]["delta_intrinsic_vs_A"]
    assert abs(b3) > 3 * abs(b2)
